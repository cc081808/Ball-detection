// Compile-time regression checks: no motor movement.
#include "control.h"
#include "vision_assist.h"
constexpr BallCheck checking = beginBallCheck({'Y', 0, false, 10}, 1000);
constexpr BallCheck early = ballCheckStep(checking, {'Y', 0, false, 11}, 1100);
constexpr BallCheck before_aim = ballCheckStep(checking, {'Y', 200, false, 12}, 1200);
constexpr BallCheck one = ballCheckStep(checking, {'Y', 40, false, 13}, 1200);
constexpr BallCheck two = ballCheckStep(one, {'Y', 50, false, 14}, 1300);
static_assert(!ballApproved(checking), "a prior camera observation cannot approve a new sensor target");
static_assert(!ballApproved(early) && early.hits == 0, "allow the aimed view to settle");
static_assert(before_aim.hits == 0, "frame captured before aiming must not count even if recently received");
static_assert(one.hits == 1 && !ballApproved(one), "one frame is insufficient");
static_assert(ballCheckStep(one, {'Y', 70, false, 13}, 1230).hits == 1, "same frame is never counted twice");
static_assert(ballApproved(two), "two distinct fresh post-aim observations approve collection");
static_assert(!ballApproved(ballCheckStep(one, {'N', 30, false, 14}, 1300)), "no match resets confirmation");
static_assert(ballCheckStep(one, {'N', 30, false, 14}, 1300).hits == 0, "need consecutive positive observations");
static_assert(!ballApproved(ballCheckStep(two, {'Y', 751, false, 15}, 1400)), "stale data cannot approve");
static_assert(!ballApproved(ballCheckStep(two, {'Y', 20, true, 15}, 1400)), "mission stop overrides confirmation");
static_assert(!ballApproved(ballCheckStep(two, {'S', 20, false, 15}, 1400)), "invalid input revokes approval");
static_assert(!visionLive({'F', 0, false, 1}) && !visionLive({'L', 0, false, 1}), "old steering commands cannot confirm");
static_assert(visionLive({'N', 20, false, 1}), "live no-ball is not a camera outage");
constexpr MissionStartGate start_held = {true, false, false};
constexpr MissionStartGate start_released = missionStartStep(start_held, false, false);
constexpr MissionStartGate pressed_no_camera = missionStartStep(start_released, false, true);
constexpr MissionStartGate camera_connected_held = missionStartStep(pressed_no_camera, true, true);
constexpr MissionStartGate start_waiting = missionStartStep(camera_connected_held, true, false);
constexpr MissionStartGate start_pressed = missionStartStep(start_waiting, true, true);
static_assert(!pressed_no_camera.ready && !pressed_no_camera.press_armed, "no camera cannot arm a start");
static_assert(!camera_connected_held.ready && !camera_connected_held.press_armed, "connection while held cannot start");
static_assert(!start_waiting.ready, "camera connection alone never starts motion");
static_assert(missionStartStep(start_pressed, true, false).ready, "fresh press and release starts with live camera");
static_assert(!missionStartStep(start_pressed, false, false).ready, "camera loss while releasing returns to waiting");
static_assert(visionLive({'N', 450, false, 1}), "normal inference age does not cause a startup bounce");
constexpr BallCheck slower_first = ballCheckStep(checking, {'Y', 350, false, 30}, 1500);
static_assert(ballApproved(ballCheckStep(slower_first, {'Y', 350, false, 31}, 1900)), "two post-aim CPU frames can confirm");
constexpr BumpState clear_bump = {BumpPhase::CLEAR, 0};
constexpr BumpState backing = bumperStep(clear_bump, true, true, 100);
constexpr BumpState turning = bumperStep(backing, false, true, 700);
static_assert(backing.phase == BumpPhase::BACKOFF, "bumper starts bounded reverse");
static_assert(bumperWheels(backing.phase).left < 0 && bumperWheels(backing.phase).right < 0, "reverse both wheels");
static_assert(bumperStep(backing, true, true, 699).phase == BumpPhase::BACKOFF, "backoff deadline");
static_assert(bumperStep(backing, true, true, 700).phase == BumpPhase::BLOCKED, "stuck bumper cannot reverse forever");
static_assert(turning.phase == BumpPhase::TURN, "released bumper turns away after reverse");
static_assert(bumperStep(turning, false, true, 1700).phase == BumpPhase::CLEAR, "recovery resumes camera");
static_assert(bumperStep(turning, true, true, 800).phase == BumpPhase::BLOCKED, "contact during turn stops");
static_assert(bumperStep(backing, true, false, 200).phase == BumpPhase::CLEAR, "pause or stale data cancels reverse");
static_assert(bumperStep(turning, false, false, 800).phase == BumpPhase::CLEAR, "pause or stale data cancels turn");
static_assert(bumperStep(clear_bump, true, false, 0).phase == BumpPhase::CLEAR, "idle bumper cannot start motion");
constexpr CameraState none = {false, false, 0};
constexpr CameraState approached = cameraStep(none, 'F', true, 100);
constexpr CameraState finishing = cameraStep(approached, 'C', true, 200);
static_assert(cameraAction(finishing, 'C', 799) == 'F', "bounded finish advances");
static_assert(cameraAction(finishing, 'C', 800) == 'N', "finish expires into search");
static_assert(cameraAction(cameraStep(finishing, 'C', true, 1000), 'C', 1000) == 'N', "repeated C cannot extend finish");
static_assert(!cameraStep(finishing, 'C', false, 210).finishing, "watchdog or pause cancels finish");
static_assert(!cameraStep(finishing, 'S', true, 210).finishing, "explicit stop cancels finish");
static_assert(!cameraStep(none, 'C', true, 100).finishing, "cannot start blind without actual approach");
static_assert(!cameraStep(finishing, 'L', true, 210).finishing, "reacquired target cancels blind motion");
static_assert(searchWheels(0).left < 0 && searchWheels(8000).left > 0, "search reverses periodically");
static_assert(canStartCollector(true, true, true, true, false, false, false), "select V4");
static_assert(!canStartCollector(true, true, true, true, true, false, false), "held button cannot start V4");
static_assert(!canStartCollector(true, true, true, true, false, true, false), "exclusive mode selection");
static_assert(canStartCollector(true, false, true, true, false, false, false), "V4 works without controller");
static_assert(!canStartCollector(true, true, false, true, false, false, false), "V4 needs centred sticks");
static_assert(!canStartCollector(true, true, true, true, false, false, true), "pause overrides V4 start");
static_assert(!canStartCollector(false, true, true, true, false, false, false), "stop overrides V4 start");
static_assert(chooseMode(Mode::IDLE, true, false, false, false, true, true) == Mode::IDLE, "startup idle");
static_assert(chooseMode(Mode::IDLE, true, false, true, false, true, true) == Mode::AUTO, "start auto");
static_assert(chooseMode(Mode::IDLE, true, false, true, false, true, false) == Mode::IDLE, "no auto without camera");
static_assert(chooseMode(Mode::AUTO, true, false, false, false, true, false) == Mode::IDLE, "stale data disarms auto");
static_assert(chooseMode(Mode::IDLE, true, false, false, false, true, true) == Mode::IDLE, "recovery needs new press");
static_assert(chooseMode(Mode::AUTO, false, false, false, false, true, true) == Mode::AUTO, "camera works without controller");
static_assert(chooseMode(Mode::IDLE, false, false, true, false, true, true) == Mode::AUTO, "physical camera start without controller");
static_assert(chooseMode(Mode::MANUAL, false, false, false, false, true, true) == Mode::IDLE, "manual stops on controller loss");
static_assert(chooseMode(Mode::IDLE, false, false, false, true, true, true) == Mode::IDLE, "manual requires controller");
static_assert(chooseMode(Mode::AUTO, false, true, true, false, true, true) == Mode::IDLE, "physical pause beats start");
static_assert(chooseMode(Mode::AUTO, false, false, false, false, true, false) == Mode::IDLE, "no-controller camera still has watchdog");
static_assert(chooseMode(Mode::MANUAL, true, true, true, false, true, true) == Mode::IDLE, "stop has priority");
static_assert(chooseMode(Mode::IDLE, true, false, false, true, true, false) == Mode::MANUAL, "manual needs no camera");
static_assert(chooseMode(Mode::IDLE, true, false, false, true, false, true) == Mode::IDLE, "centre sticks to start");
static_assert(chooseMode(Mode::AUTO, true, false, true, true, true, true) == Mode::IDLE, "conflicting mode buttons stop");
static_assert(manualWheels(4, -4).left == 0 && manualWheels(4, -4).right == 0, "deadband");
static_assert(manualWheels(100, 0).left == 100 && manualWheels(100, 0).right == 100, "full manual speed");
static_assert(manualWheels(100, 100).left == 100 && manualWheels(100, 100).right == 25, "arcade normalization");
static_assert(manualWheels(-100, 0).left == -100, "reverse");
static_assert(cameraWheels('L').left < 0 && cameraWheels('L').right > 0, "left turn");
static_assert(cameraWheels('R').left > 0 && cameraWheels('R').right < 0, "right turn");
static_assert(cameraWheels('F').left == 15 && cameraWheels('F').right == 15, "slow approach");
static_assert(cameraWheels('S').left == 0 && cameraWheels('?').right == 0, "no target stop");
